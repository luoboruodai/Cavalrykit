#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn every_key_has_four_translations_and_matching_placeholders() {
        fn placeholders(s: &str) -> Vec<&str> {
            s.split('{')
                .skip(1)
                .map(|s| s.split('}').next().unwrap())
                .collect()
        }
        for key in ALL {
            let mut expected = placeholders(Language::En.tr(*key));
            expected.sort();
            for language in Language::ALL {
                let text = language.tr(*key);
                assert!(!text.trim().is_empty());
                let mut found = placeholders(text);
                found.sort();
                assert_eq!(found, expected, "{key:?} {language:?}");
            }
        }
    }
}
